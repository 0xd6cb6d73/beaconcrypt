def transform(source: bytes) -> bytes:
    text = source.decode()
    if re.search(
        r"(?m)^\s*(?:axiom|opaque|unsafe|partial)\b|\b(?:sorry|admit)\b", text
    ):
        raise ValueError("unchecked source file declaration")
    declarations = re.findall(r"^def ([^\s]+)", text, re.M)
    marker = "def " + DECLARATION + "\n"
    if declarations != [DECLARATION] or text.count(marker) != 1:
        raise ValueError("seal join declaration roster changed")
    start = text.index(marker)
    end = text.index("\nend beaconcrypt_seal_join", start)
    body = text[start:end].strip() + "\n"
    if hashlib.sha256(body.encode()).hexdigest() != REVIEWED_BODY:
        raise ValueError("source seal join body changed")
    if hashlib.sha256(source).hexdigest() != REVIEWED_SOURCE:
        raise ValueError("source seal join whole file changed")
    body = body.replace(marker, "def join\n", 1)
    for before, after, count in REPLACEMENTS:
        if body.count(before) != count:
            raise ValueError("seal join leaf multiplicity changed: " + before)
        body = body.replace(before, after)
    body, residuals = RESIDUAL.subn("Lifted.fromResidual", body)
    if residuals != 3:
        raise ValueError("seal join residual branch roster changed")
    if re.search(
        r"\b(?:RustM|ok)\b|Array\.index_usize|core\.slice\.Slice\.len|core\.num\.Usize\.checked_add"
        r"|alloc\.vec\.Vec\.(?:new|try_reserve_exact|extend_from_slice)|core\.result\.Result\.ok"
        r"|core\.option\.Option\.Insts\.",
        body,
    ):
        raise ValueError("unlifted seal join operation")
    return (
        HEADER
        + "-- Extracted input SHA-256: "
        + hashlib.sha256(source).hexdigest()
        + "\n-- Transformation SHA-256: "
        + hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
        + "\n\n"
        + body
        + "\nend BeaconcryptCore.Refinement.AdapterSealJoinRequestExtraction\n"
    ).encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, help="isolated development output path")
    args = parser.parse_args()
    expected = transform((ROOT / SOURCE).read_bytes())
    destination = args.output if args.output is not None else ROOT / DESTINATION
    if args.write:
        destination.write_bytes(expected)
    elif not destination.exists() or destination.read_bytes() != expected:
        parser.error("seal join request extraction differs; review the generated diff")
    print("seal join requests match the exact reviewed source body and leaves")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
