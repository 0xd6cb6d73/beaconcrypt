"""Extract original preflight with checked finite traversal/std slice preparation.

Production generated code is unchanged. Existing core extraction supplies the
actual message-size predicate. This component adds no parser law or external
correctness premise and does not assert complete registration codec closure.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile

import check_registration_codec_extraction as checkpoint
import extract_registration_primitives as primitives
import prepare_registration_preflight_source as preparation
from extract_frame_codec import configuration, isolated_work

ROOT = checkpoint.ROOT
SUBDIRECTORY = "BeaconcryptCore/RegistrationPreflightExtraction"
DESTINATION = ROOT / "beaconcrypt-core/proofs/lean" / SUBDIRECTORY
CERTIFICATE_DESTINATION = (
    ROOT
    / "beaconcrypt-core/proofs/lean/BeaconcryptCore/Refinement/RegistrationPreflightSourceCertificates.lean"
)
COHORT = "registration-preflight"
ENTRIES = (
    "preflight",
    "primitive_argument",
    "extraction_preflight_field",
    "extraction_argument_long",
    "extraction_argument_word",
    "extraction_strip_prefix",
)
NAMESPACE = "namespace beaconcrypt_parse\n"
MODELS = {
    "TypesExternal.lean": "import Aeneas\n\nset_option warningAsError true\n",
    "FunsExternal.lean": "import BeaconcryptCore.RegistrationPreflightExtraction.Types\nimport BeaconcryptCore.Extraction.Funs\nimport BeaconcryptCore.Refinement.RegistrationCodecStandardSlices\n\nset_option warningAsError true\n",
}
INSTALLED = (
    "Types.lean",
    "Funs.lean",
    "TypesExternal.lean",
    "FunsExternal.lean",
    "external-signatures.json",
)


def source_snapshot(root: Path = ROOT) -> dict[str, str]:
    result = preparation.source_snapshot(root)
    for name in (
        "scripts/extract_registration_preflight.py",
        "scripts/extract_registration_primitives.py",
        "beaconcrypt-core/proofs/lean/BeaconcryptCore/Extraction/Funs.lean",
        "beaconcrypt-core/proofs/lean/BeaconcryptCore/Extraction/Types.lean",
    ):
        result[name] = checkpoint.digest((root / name).read_bytes())
    return result


UNIT_SOME_ORIGINAL = "core.bool.Bool.then_some"
UNIT_SOME_MODEL = (
    "BeaconcryptCore.Refinement.RegistrationCodecStandardSlices.thenSomeUnit"
)
BOOL_SOURCE_SHA256 = "7e96cdc4559d0884c027ffc5de3c6e5bdaf0a0dbdc0e01339159f2062ce05a80"
BOOL_SIGNATURE_SHA256 = (
    "f270892a4b98a52fd353214997e752a92c5f78671d931a7a87d1f5d9181491b7"
)
BOOL_BODY_SHA256 = "a91eb4368e3c233211c566862e6bbc79a48984ee0b6b1204bbbd7495968c2161"


def unit_bool_evidence(evidence: dict | None = None) -> dict:
    if evidence is None:
        path = preparation.STD_SOURCE.parent.parent / "bool.rs"
        raw = path.read_bytes()
        if checkpoint.digest(raw) != BOOL_SOURCE_SHA256:
            raise ValueError("unreviewed standard bool source")
        signature, body = preparation.function_body(
            raw.decode(),
            r"pub const fn then_some<T: \[const\] Destruct>\(self, t: T\) -> Option<T>",
        )
        evidence = {
            "source_sha256": BOOL_SOURCE_SHA256,
            "signature": signature,
            "body": body,
            "monomorphic_type": "Unit",
            "argument_evaluated_before_call": True,
        }
    if not isinstance(evidence, dict) or set(evidence) != {
        "source_sha256",
        "signature",
        "body",
        "monomorphic_type",
        "argument_evaluated_before_call",
    }:
        raise ValueError("standard bool evidence roster drift")
    if (
        evidence["source_sha256"] != BOOL_SOURCE_SHA256
        or checkpoint.digest(evidence["signature"].encode()) != BOOL_SIGNATURE_SHA256
        or checkpoint.digest(evidence["body"].encode()) != BOOL_BODY_SHA256
        or evidence["monomorphic_type"] != "Unit"
        or evidence["argument_evaluated_before_call"] is not True
    ):
        raise ValueError("standard bool Unit specialization drift")
    return evidence


def normalize(value: bytes, name: str) -> tuple[bytes, str]:
    checkpoint.checked_lean(value, name)
    source = value.decode()
    if source.count(NAMESPACE) != 1:
        raise ValueError("preflight generated namespace drift")
    header, body = source.split(NAMESPACE)
    raw_header = header
    if not header.startswith("-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS\n"):
        raise ValueError("missing preflight generator header")
    for linter in primitives.LINTERS:
        option = "set_option linter." + linter + " false\n"
        if header.count(option) != 1:
            raise ValueError("preflight header linter roster drift")
        header = header.replace(option, "")
    if "set_option linter." in header or "set_option warningAsError" in header:
        raise ValueError("unreviewed preflight generator option")
    lines = header.splitlines(keepends=True)
    last_import = max(
        index for index, line in enumerate(lines) if line.startswith("import ")
    )
    lines.insert(last_import + 1, "\nset_option warningAsError true\n")
    body = primitives.identifiers(body)
    if name == "Funs.lean":
        if (
            body.count(UNIT_SOME_ORIGINAL) != 1
            or body.count(UNIT_SOME_ORIGINAL + " b1 ()") != 1
        ):
            raise ValueError("then_some must have the exact Unit-only call signature")
        body = body.replace(UNIT_SOME_ORIGINAL, UNIT_SOME_MODEL)
    return ("".join(lines) + NAMESPACE + body).encode(), raw_header


def checked_entries(value: bytes) -> None:
    source = checkpoint.code(value)
    for entry in ENTRIES:
        if len(re.findall(r"^def " + re.escape(entry) + r"\b", source, re.M)) != 1:
            raise ValueError("preflight generated entry-point roster drift")


def assemble(generated: Path) -> tuple[dict[str, bytes], dict]:
    contents, headers, hashes, templates = {}, {}, {}, {}
    for name in ("Types.lean", "Funs.lean"):
        raw = (generated / name).read_bytes()
        contents[name], headers[name] = normalize(raw, name)
        hashes[name] = checkpoint.digest(raw)
    checked_entries(contents["Funs.lean"])
    for path in sorted(generated.glob("*_Template.lean")):
        raw = path.read_bytes()
        checkpoint.checked_template(raw)
        hashes[path.name] = checkpoint.digest(raw)
        templates[path.name] = {"source": raw.decode(), "sha256": hashes[path.name]}
    if set(templates) != {"TypesExternal_Template.lean", "FunsExternal_Template.lean"}:
        raise ValueError("preflight external template roster drift")
    contents.update({name: value.encode() for name, value in MODELS.items()})
    contents["external-signatures.json"] = (
        json.dumps(templates, indent=2, sort_keys=True) + "\n"
    ).encode()
    return contents, {
        "raw_headers": headers,
        "raw_generated_sha256": hashes,
        "external_templates": templates,
    }


def check_source(
    root: Path = ROOT,
    destination: Path = DESTINATION,
    certificate: Path = CERTIFICATE_DESTINATION,
) -> None:
    configuration(root)
    provenance = json.loads((destination / "provenance.json").read_text())
    if provenance.get("source_sha256") != source_snapshot(root):
        raise ValueError("preflight source provenance drift")
    if provenance.get("tools") != checkpoint.TOOLS or provenance.get(
        "rust_start_from"
    ) != list(ENTRIES):
        raise ValueError("preflight entry/tool roster drift")
    if provenance.get("public_codec_law_proved") is not False:
        raise ValueError("preflight component cannot assert a public codec law")
    primitives.hash_roster(
        provenance.get("tool_sha256"), set(checkpoint.TOOLS), "tool_sha256"
    )
    unit_bool_evidence(provenance["unit_bool_standard_source"])
    prepared, lean, manifest = preparation.expected(
        root, std_evidence=provenance["source_preparation"]["standard_library"]
    )
    if (
        provenance.get("source_preparation") != manifest
        or provenance.get("prepared_lib") != prepared
    ):
        raise ValueError("preflight source/control/std normalization drift")
    if certificate.read_text() != lean:
        raise ValueError("preflight finite control certificate drift")
    installed = primitives.hash_roster(
        provenance.get("installed_sha256"), set(INSTALLED), "installed_sha256"
    )
    raw = primitives.hash_roster(
        provenance.get("raw_generated_sha256"),
        {
            "Types.lean",
            "Funs.lean",
            "TypesExternal_Template.lean",
            "FunsExternal_Template.lean",
        },
        "raw_generated_sha256",
    )
    if set(provenance["raw_headers"]) != {"Types.lean", "Funs.lean"}:
        raise ValueError("preflight header evidence drift")
    for name in INSTALLED:
        if checkpoint.digest((destination / name).read_bytes()) != installed[name]:
            raise ValueError("preflight installed file drift: " + name)
    for name in ("Types.lean", "Funs.lean"):
        _, body = (destination / name).read_text().split(NAMESPACE)
        if name == "Funs.lean":
            if body.count(UNIT_SOME_MODEL) != 1:
                raise ValueError("missing Unit platform call")
            body = body.replace(UNIT_SOME_MODEL, UNIT_SOME_ORIGINAL)
        body = primitives.identifiers(body, reverse=True)
        restored = (provenance["raw_headers"][name] + NAMESPACE + body).encode()
        normalized, _ = normalize(restored, name)
        if (
            normalized != (destination / name).read_bytes()
            or checkpoint.digest(restored) != raw[name]
        ):
            raise ValueError("preflight generated-body reconstruction drift")
    checked_entries((destination / "Funs.lean").read_bytes())
    for name, expected in MODELS.items():
        if (destination / name).read_text() != expected:
            raise ValueError("preflight external files must contain imports only")
    templates = json.loads((destination / "external-signatures.json").read_text())
    if (
        set(templates) != {"TypesExternal_Template.lean", "FunsExternal_Template.lean"}
        or templates != provenance["external_templates"]
    ):
        raise ValueError("preflight external evidence roster drift")
    for name, item in templates.items():
        checkpoint.checked_template(item["source"].encode())
        if (
            checkpoint.digest(item["source"].encode()) != raw[name]
            or item["sha256"] != raw[name]
        ):
            raise ValueError("preflight external evidence body drift")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--write", action="store_true")
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--check-source", action="store_true")
    parser.add_argument("--work-dir", type=Path)
    parser.add_argument("--std-source", type=Path, default=preparation.STD_SOURCE)
    parser.add_argument("--timeout", type=int, default=120)
    parser.add_argument(
        "--tools-root",
        type=Path,
        default=Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache"))
        / "hax/tools",
    )
    args = parser.parse_args()
    try:
        if args.check_source:
            check_source()
            print(
                "Original preflight/std source, strict cohort and finite certificates match"
            )
            return 0
        if args.work_dir is None or args.timeout <= 0:
            raise ValueError(
                "extraction requires external work directory and positive timeout"
            )
        configuration()
        before = source_snapshot()
        parent = isolated_work(args.work_dir)
        parent.mkdir(parents=True, exist_ok=True)
        work = Path(tempfile.mkdtemp(prefix="registration-preflight-", dir=parent))
        fixture = work / "source"
        preparation.prepare(fixture, std_source=args.std_source)
        (fixture / "scripts").mkdir()
        for name in (
            "check_registration_codec_extraction.py",
            "extract_frame_codec.py",
        ):
            (fixture / "scripts" / name).write_bytes(
                (ROOT / "scripts" / name).read_bytes()
            )
        tools = {
            name: args.tools_root / name / version / name
            for name, version in checkpoint.TOOLS.items()
        }
        original_root, original_snapshot, original_subdirectory = (
            checkpoint.ROOT,
            checkpoint.snapshot,
            checkpoint.SUBDIRECTORY,
        )
        try:
            checkpoint.ROOT = fixture
            checkpoint.snapshot = lambda: original_snapshot(fixture)
            checkpoint.SUBDIRECTORY = SUBDIRECTORY
            checkpoint.COHORTS[COHORT] = ENTRIES
            report = checkpoint.run(work, tools, COHORT, args.timeout, False)
        finally:
            checkpoint.ROOT = original_root
            checkpoint.snapshot = original_snapshot
            checkpoint.SUBDIRECTORY = original_subdirectory
            checkpoint.COHORTS.pop(COHORT, None)
        if report["status"] != "extracted-without-external-obligations":
            raise ValueError(
                "preflight extraction blocked: "
                + str(report.get("error"))
                + "; "
                + str(work / "report.json")
            )
        contents, evidence = assemble(work / "generated" / SUBDIRECTORY)
        prepared, lean, manifest = preparation.expected(std_source=args.std_source)
        if before != source_snapshot():
            raise ValueError("preflight source changed during extraction")
        provenance = {
            "tools": checkpoint.TOOLS,
            "rust_start_from": ENTRIES,
            "tool_sha256": report["tool_sha256"],
            "source_sha256": before,
            "source_preparation": manifest,
            "prepared_lib": prepared,
            **evidence,
            "installed_sha256": {
                name: checkpoint.digest(value) for name, value in contents.items()
            },
            "public_codec_law_proved": False,
            "unit_bool_standard_source": unit_bool_evidence(),
        }
        contents["provenance.json"] = (
            json.dumps(provenance, indent=2, sort_keys=True) + "\n"
        ).encode()
        if args.write:
            DESTINATION.mkdir(parents=True, exist_ok=True)
            for name, value in contents.items():
                (DESTINATION / name).write_bytes(value)
            CERTIFICATE_DESTINATION.write_text(lean)
            check_source()
            print(
                "Wrote actual complete preflight source cohort, standard provenance and finite control certificates"
            )
        else:
            changed = [
                name
                for name, value in contents.items()
                if not (DESTINATION / name).is_file()
                or (DESTINATION / name).read_bytes() != value
            ]
            if changed:
                raise ValueError(
                    "preflight fresh-extraction drift: " + ",".join(changed)
                )
            print("Actual preflight source cohort matches fresh pinned extraction")
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
