/// The deterministic, unsigned payloads of an InitKex message.
///
/// The adapter signs `prekey`, `one_time_key`, and `pq_key`, then places the
/// resulting signed buffers and `identity_key` into Cap'n Proto. The X25519
/// payloads are `[type, role, key]`; validation assigns meaning from the
/// authenticated role byte rather than from the wire field position alone.
#[derive(Clone, Copy)]
#[cfg_attr(not(hax_compilation), derive(Debug, Eq, PartialEq))]
pub struct InitKex {
	identity_key: [u8; ENCODED_SIGN_PUBLIC_KEY_SIZE],
	prekey: [u8; ENCODED_X25519_PUBLIC_KEY_SIZE],
	one_time_key: [u8; ENCODED_X25519_PUBLIC_KEY_SIZE],
	pq_key: [u8; ENCODED_MLKEM768_PUBLIC_KEY_SIZE],
}

impl InitKex {
	pub const fn from_encoded(
		identity_key: [u8; ENCODED_SIGN_PUBLIC_KEY_SIZE],
		prekey: [u8; ENCODED_X25519_PUBLIC_KEY_SIZE],
		one_time_key: [u8; ENCODED_X25519_PUBLIC_KEY_SIZE],
		pq_key: [u8; ENCODED_MLKEM768_PUBLIC_KEY_SIZE],
	) -> Self {
		Self {
			identity_key,
			prekey,
			one_time_key,
			pq_key,
		}
	}

	pub const fn identity_key(&self) -> &[u8; ENCODED_SIGN_PUBLIC_KEY_SIZE] {
		&self.identity_key
	}

	pub const fn prekey(&self) -> &[u8; ENCODED_X25519_PUBLIC_KEY_SIZE] {
		&self.prekey
	}

	pub const fn one_time_key(&self) -> &[u8; ENCODED_X25519_PUBLIC_KEY_SIZE] {
		&self.one_time_key
	}

	pub const fn pq_key(&self) -> &[u8; ENCODED_MLKEM768_PUBLIC_KEY_SIZE] {
		&self.pq_key
	}
}

/// Signature-checked and type-checked InitKex public keys.
#[derive(Clone, Copy)]
#[cfg_attr(not(hax_compilation), derive(Debug, Eq, PartialEq))]
pub struct VerifiedInitKex {
	beacon_identity_public_key: [u8; SIGN_PUBLIC_KEY_SIZE],
	beacon_prekey_public_key: [u8; X25519_PUBLIC_KEY_SIZE],
	beacon_one_time_public_key: [u8; X25519_PUBLIC_KEY_SIZE],
	beacon_pq_public_key: [u8; MLKEM768_PUBLIC_KEY_SIZE],
}

impl VerifiedInitKex {
	pub const fn beacon_identity_public_key(&self) -> &[u8; SIGN_PUBLIC_KEY_SIZE] {
		&self.beacon_identity_public_key
	}

	pub const fn beacon_prekey_public_key(&self) -> &[u8; X25519_PUBLIC_KEY_SIZE] {
		&self.beacon_prekey_public_key
	}

	pub const fn beacon_one_time_public_key(&self) -> &[u8; X25519_PUBLIC_KEY_SIZE] {
		&self.beacon_one_time_public_key
	}

	pub const fn beacon_pq_public_key(&self) -> &[u8; MLKEM768_PUBLIC_KEY_SIZE] {
		&self.beacon_pq_public_key
	}

	/// Stable, authenticated identifier for this one-time registration.
	///
	/// Exact equality is used by the adapter's consumed-registration set; no
	/// hash or collision-resistance assumption is needed.
	pub fn registration_id(&self) -> RegistrationId {
		let bytes: [u8; REGISTRATION_ID_SIZE] = core::array::from_fn(|i| {
			if i < SIGN_PUBLIC_KEY_SIZE {
				self.beacon_identity_public_key[i]
			} else {
				self.beacon_one_time_public_key[i - SIGN_PUBLIC_KEY_SIZE]
			}
		});
		RegistrationId { bytes }
	}
}

/// Production abstraction used by the replay adapter and the ProVerif model.
///
/// The backend replacement below is deliberately limited to the exact
/// identity/one-time-key projection proved by the Lean PQXDH refinement. It does
/// not replace the Rust implementation on ordinary builds.
#[cfg_attr(
	feature = "proverif",
	hax_lib::proverif::replace(
		"reduc forall identity: bitstring, prekey: bitstring, one_time: bitstring, pq: bitstring;\n  ${registration_id}(beaconcrypt_core__pqxdh__VerifiedInitKex(identity, prekey, one_time, pq)) = beaconcrypt_core__pqxdh__RegistrationId(registration_identifier(identity, one_time))."
	)
)]
pub fn registration_id(registration: &VerifiedInitKex) -> RegistrationId {
	registration.registration_id()
}

