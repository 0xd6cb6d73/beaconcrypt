def digest(contents: bytes) -> str:
    return hashlib.sha256(contents).hexdigest()


def transform(source: bytes) -> bytes:
    if digest(source) != SOURCE_SHA256:
        raise ValueError("unreviewed original seal source file")
    text = source.decode()
    if text.count(DECLARATION) != 1:
        raise ValueError("original seal declaration roster changed")
    if re.search(r"\b(?:sorry|sorryAx|admit|axiom|opaque|unsafe|partial)\b", text):
        raise ValueError("unchecked original seal source")
    start = text.index(DECLARATION)
    end = text.index("\nend beaconcrypt_seal", start)
    body = text[start:end].strip() + "\n"
    if digest(body.encode()) != BODY_SHA256:
        raise ValueError("original seal body changed")
    body = body.replace(DECLARATION, "def execute\n", 1)
    for before, after, count in REPLACEMENTS:
        if body.count(before) != count:
            raise ValueError("seal leaf multiplicity changed: " + before)
        body = body.replace(before, after)
    for pattern, replacement, count, label in (
        (TAG, "Lifted.tag", 2, "tag conversion"),
        (RESIDUAL, "Lifted.fromResidual", 6, "residual branch"),
        (
            SUCCESS,
            r"pure (core.option.Option.Some (ciphertext, \1))",
            2,
            "success branch",
        ),
    ):
        body, actual = pattern.subn(replacement, body)
        if actual != count:
            raise ValueError("seal " + label + " roster changed")
    if re.search(
        r"\b(?:RustM|ok)\b|core\.convert\.Into|core\.array\.Array\.as_slice"
        r"|beaconcrypt_crypto\.|ratchet\.join_record_parts|alloc\.vec\.Vec\.as_slice"
        r"|core\.Array\.Insts\.|core\.option\.Option\.Insts\.|core\.result\.Result\.ok"
        r"|zeroize\.Zeroizing\.|core\.option\.Option\.as_ref",
        body,
    ):
        raise ValueError("unlifted original seal operation")
    return (
        HEADER
        + "-- Extracted input SHA-256: "
        + digest(source)
        + "\n-- Transformation SHA-256: "
        + digest(Path(__file__).read_bytes())
        + "\n\n"
        + body
        + "\nend BeaconcryptCore.Refinement.AdapterSealRequestExtraction\n"
    ).encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    expected = transform((ROOT / SOURCE).read_bytes())
    destination = args.output if args.output is not None else ROOT / DESTINATION
    if args.write:
        destination.write_bytes(expected)
    elif not destination.exists() or destination.read_bytes() != expected:
        parser.error("seal request extraction differs; review the generated diff")
    print("seal requests match the complete reviewed source dispatcher")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
