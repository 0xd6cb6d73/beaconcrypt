pub const SIGN_PUBLIC_KEY_SIZE: usize = 32;
pub const X25519_PUBLIC_KEY_SIZE: usize = 32;
pub const MLKEM768_PUBLIC_KEY_SIZE: usize = 1_184;
pub const MLKEM768_CIPHERTEXT_SIZE: usize = 1_088;
pub const SHARED_SECRET_SIZE: usize = 32;
pub const DH_SECRET_SIZE: usize = 32;
pub const PQXDH_PADDING_SIZE: usize = 32;
pub const RATCHET_CHAIN_SIZE: usize = crate::ratchet::RATCHET_CHAIN_SIZE;
/// Number of bytes returned when the session root is expanded into both directional chains.
pub const INITIAL_RATCHET_KDF_OUTPUT_SIZE: usize = RATCHET_CHAIN_SIZE * 2;
const _: () = assert!(INITIAL_RATCHET_KDF_OUTPUT_SIZE == 64);
pub const REGISTRATION_KEY_ID_BINDING_SIZE: usize = 8;
pub const REGISTRATION_ID_SIZE: usize = SIGN_PUBLIC_KEY_SIZE + X25519_PUBLIC_KEY_SIZE;

pub const SIGN_TYPE_ED25519: u8 = 1;
pub const KEM_TYPE_MLKEM768: u8 = 3;
pub const KEM_TYPE_X25519: u8 = 4;

/// Key-role markers occupy the high half of the byte domain, while all
/// algorithm/type markers occupy the low half. This makes a type byte
/// impossible to reinterpret as a role byte.
pub const KEY_ROLE_PREKEY: u8 = 0x80;
pub const KEY_ROLE_ONE_TIME: u8 = 0x81;

pub const ENCODED_SIGN_PUBLIC_KEY_SIZE: usize = SIGN_PUBLIC_KEY_SIZE + 1;
pub const ENCODED_X25519_PUBLIC_KEY_SIZE: usize = X25519_PUBLIC_KEY_SIZE + 2;
pub const ENCODED_MLKEM768_PUBLIC_KEY_SIZE: usize = MLKEM768_PUBLIC_KEY_SIZE + 1;

// https://signal.org/docs/specifications/pqxdh/#pqxdh-parameters
pub const PQXDH_INFO: &[u8; 46] = b"BeaconcryptPqxdh_CURVE25519_SHA-512_ML-KEM-768";
pub const SYM_RATCHET_INFO_SIZE: usize = crate::ratchet::SYM_RATCHET_INFO_SIZE;
pub const SYM_RATCHET_INFO: &[u8; SYM_RATCHET_INFO_SIZE] = crate::ratchet::SYM_RATCHET_INFO;

pub const ROOT_KEY_INPUT_SIZE: usize =
	PQXDH_PADDING_SIZE + (4 * DH_SECRET_SIZE) + SHARED_SECRET_SIZE;
pub const ASSOCIATED_DATA_SIZE: usize = crate::constants::ASSOCIATED_DATA_SIZE;

// The fixed ranges below are deliberately literal so hax exposes exact slice
// boundaries to Lean. Keep those proof-visible bounds tied to the public sizes.
const _: () = assert!(SIGN_PUBLIC_KEY_SIZE == 32);
const _: () = assert!(X25519_PUBLIC_KEY_SIZE == 32);
const _: () = assert!(MLKEM768_PUBLIC_KEY_SIZE == 1_184);
const _: () = assert!(DH_SECRET_SIZE == 32);
const _: () = assert!(SHARED_SECRET_SIZE == 32);
const _: () = assert!(RATCHET_CHAIN_SIZE == 32);
const _: () = assert!(ROOT_KEY_INPUT_SIZE == 192);
const _: () = assert!(ASSOCIATED_DATA_SIZE == 153);
const _: () = assert!(REGISTRATION_KEY_ID_BINDING_SIZE == 8);
const _: () = assert!(REGISTRATION_ID_SIZE == 64);
const _: () = assert!(SIGN_TYPE_ED25519 < 0x80);
const _: () = assert!(KEM_TYPE_MLKEM768 < 0x80);
const _: () = assert!(KEM_TYPE_X25519 < 0x80);
const _: () = assert!(KEY_ROLE_PREKEY >= 0x80);
const _: () = assert!(KEY_ROLE_ONE_TIME >= 0x80);
const _: () = assert!(!(KEY_ROLE_PREKEY == KEY_ROLE_ONE_TIME));

#[derive(Clone, Copy)]
