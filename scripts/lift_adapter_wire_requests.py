def transform(source: bytes) -> bytes:
    text = source.decode()
    if (
        text.count("def wire.encode_record\n") != 1
        or text.count("\nend beaconcrypt") != 1
    ):
        raise ValueError("writer declaration roster changed")
    body = (
        "def wire.encode_record\n"
        + text.split("def wire.encode_record\n", 1)[1]
        .split("\nend beaconcrypt", 1)[0]
        .rstrip()
        + "\n"
    )
    if hashlib.sha256(body.encode()).hexdigest() != REVIEWED_BODY_SHA256:
        raise ValueError("source-derived writer body changed; review before updating")
    if re.search(r"\b(?:sorry|admit|axiom|opaque|unsafe|partial)\b", body):
        raise ValueError("unchecked source-derived declaration")
    for old, new, count in REPLACEMENTS:
        if body.count(old) != count:
            raise ValueError(f"reviewed writer leaf multiplicity changed: {old}")
        body = body.replace(old, new)
    if re.search(
        r"\b(?:RustM|ok|beaconcrypt)\b|core\.ops\.function|alloc\.vec\.Vec\.", body
    ):
        raise ValueError("unlifted writer leaf")
    return (
        HEADER
        + "-- Extracted input SHA-256: "
        + hashlib.sha256(source).hexdigest()
        + "\n"
        + "-- Transformation SHA-256: "
        + hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
        + "\n"
        + body
        + "\nend BeaconcryptCore.Refinement.AdapterWireRequestExtraction\n"
    ).encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = transform((ROOT / SOURCE).read_bytes())
    destination = ROOT / DESTINATION
    if args.write:
        destination.write_bytes(expected)
    elif not destination.exists() or destination.read_bytes() != expected:
        parser.error(
            "writer request extraction differs; review generated diff with --write"
        )
    print("adapter wire requests match the source-derived writer")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
