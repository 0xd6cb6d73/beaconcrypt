FOOTER = "\nend BeaconcryptCore.Refinement.AdapterRecordRequestExtraction\n"


def transform(source: bytes) -> bytes:
    text = source.decode()
    if text.count(START) != 1 or text.count(STOP) != 1:
        raise ValueError("expected exactly one selected extracted loop body")
    body = text.split(START, 1)[1].split(STOP, 1)[0]
    body = START.removeprefix("@[rust_loop_body]\n") + body.rstrip() + "\n"
    if hashlib.sha256(body.encode()).hexdigest() != REVIEWED_BODY_SHA256:
        raise ValueError(
            "selected extracted body changed; review control flow and update its reviewed fingerprint"
        )
    if re.search(r"\b(?:sorry|admit|axiom|opaque|unsafe|partial)\b", body):
        raise ValueError("unchecked declaration in extracted body")
    # Reject extra executable declarations and unexpected monadic leaves.
    if len(re.findall(r"^def\b", body, re.M)) != 1:
        raise ValueError("unexpected declaration roster")
    for old, new, expected in REPLACEMENTS:
        if body.count(old) != expected:
            raise ValueError(f"reviewed leaf {old!r} has changed multiplicity")
        body = body.replace(old, new)
    if body.count("ok ") != 6:
        raise ValueError("reviewed pure-return roster has changed")
    body = body.replace("ok ", "pure ")
    if re.search(
        r"(?<![A-Za-z0-9_.])(?:RustM\b|lift\b|ratchet\.|beaconcrypt_crypto\.|core\.option\.Option\.map\b)",
        body,
    ):
        raise ValueError("unlifted monadic leaf remains")
    source_hash = hashlib.sha256(source).hexdigest()
    transformer_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    return (
        HEADER
        + f"-- Extracted input SHA-256: {source_hash}\n"
        + f"-- Transformation SHA-256: {transformer_hash}\n"
        + body
        + FOOTER
    ).encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = transform((ROOT / SOURCE).read_bytes())
    destination = ROOT / DESTINATION
    if args.write:
        destination.write_bytes(expected)
    elif not destination.exists() or destination.read_bytes() != expected:
        parser.error(
            "request extraction differs; review the generated diff with --write"
        )
    print("adapter record request extraction matches the selected extracted body")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
