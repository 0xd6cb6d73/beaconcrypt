"""Certify exact source guard trees and their extracted constructor leaves.

The original deep branch and all other raw constructors remain arbitrary typed
effects. The actual compute_deep operation makes them unreachable for the two
registration field constructors. This is a reachable source-control certificate,
not a complete public codec, malformed parser, or native codec instance.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import check_registration_codec_extraction as checkpoint
import extract_registration_shallow as extraction
import prepare_registration_shallow_source as preparation

ROOT = checkpoint.ROOT
LEAN = Path(
    "beaconcrypt-core/proofs/lean/BeaconcryptCore/Refinement/RegistrationShallowDispatch.lean"
)
MANIFEST = Path(
    "beaconcrypt-core/proofs/lean/BeaconcryptCore/RegistrationShallowExtraction/control-correspondence.json"
)

HEADER = """-- SPDX-License-Identifier: 0BSD
-- Generated by scripts/certify_registration_shallow_dispatch.py; do not edit.
import BeaconcryptCore.RegistrationShallowExtraction.Funs
import BeaconcryptCore.Refinement.RegistrationConstructorGuards
import BeaconcryptCore.Refinement.RegistrationCodecControlNormalization
open CoreModels Aeneas
open Aeneas.Std hiding namespace core alloc
open RustM
set_option autoImplicit false
set_option warningAsError true
/-! The exact original compute_deep control and concrete extracted constructor
leaves. Deep and other-constructor branches remain arbitrary complete effects;
actual Int/String guards derive that those branches are unreachable. This source
control certificate does not assert a complete public codec or native instance. -/
namespace BeaconcryptCore.Refinement.RegistrationShallowDispatch
open beaconcrypt_parse cbordetveraux RegistrationCodecControlNormalization
"""


def operation(name: str, result: str, output: str, offset: bool) -> str:
    tail = " (offset : Usize)" if offset else ""
    args = " offset" if offset else ""
    call = "Serialize" if offset else "Size"
    return f"""
abbrev {call} := cbor_raw → Slice {output}{" → Usize" if offset else ""} → RustM {result}

def shallow{call} (other : {call}) (value : cbor_raw) (out : Slice {output}){tail} : RustM {result} :=
  match value with
  | .CBOR_Case_Int integer => extraction_{name}_shallow_int integer out{args}
  | .CBOR_Case_String string => extraction_{name}_shallow_string string out{args}
  | _ => other value out{args}

def source{call} (deep other : {call}) (value : cbor_raw) (out : Slice {output}){tail} : RustM {result} :=
  RegistrationConstructorGuards.dispatch value
    (fun _ => deep value out{args}) (fun _ => shallow{call} other value out{args})

def tree{call} (deep other : {call}) (value : cbor_raw) (out : Slice {output}){tail} :
    Tree RustM {result} :=
  .leaf (compute_deep value) fun isDeep =>
    .branch isDeep
      (.leaf (deep value out{args}) .done)
      (.leaf (shallow{call} other value out{args}) .done)

theorem tree_{name} (deep other : {call}) (value : cbor_raw) (out : Slice {output}){tail} :
    evaluate (tree{call} deep other value out{args}) = source{call} deep other value out{args} := by
  simp only [tree{call}, evaluate, bind_pure, source{call}, RegistrationConstructorGuards.dispatch]

theorem int_{name} (deep other : {call}) (integer : cbor_int) (out : Slice {output}){tail} :
    source{call} deep other (.CBOR_Case_Int integer) out{args} =
      extraction_{name}_shallow_int integer out{args} := rfl

theorem string_{name} (deep other : {call}) (string : cbor_string) (out : Slice {output}){tail} :
    source{call} deep other (.CBOR_Case_String string) out{args} =
      extraction_{name}_shallow_string string out{args} := rfl

theorem continuation_{name} {{Result : Type}} (deep other : {call}) (value : cbor_raw)
    (out : Slice {output}){tail} (next : {result} → RustM Result) :
    cps next (tree{call} deep other value out{args}) =
      source{call} deep other value out{args} >>= next := by
  rw [cps_preserves, tree_{name}]
"""


def expected(root: Path = ROOT) -> tuple[str, dict]:
    destination = root / extraction.DESTINATION.relative_to(ROOT)
    extraction.check_source(root=root, destination=destination)
    _, source = preparation.expected(root)
    dispatchers = source["dispatchers"]
    if [item["name"] for item in dispatchers] != ["ser·_d", "siz·_d"]:
        raise ValueError("original dispatcher roster drift")
    leaves = []
    for item in dispatchers:
        if item["prefix"].strip() != "let deep: bool = compute_deep(x·);":
            raise ValueError("source control guard drift")
        if len(item["helpers"]) != 2:
            raise ValueError("constructor leaf roster drift")
        for helper, expected_type, constructor in zip(
            item["helpers"],
            ("cbor_int", "cbor_string"),
            ("CBOR_Case_Int", "CBOR_Case_String"),
            strict=True,
        ):
            if helper["input"] != expected_type or helper["constructor"] != constructor:
                raise ValueError("typed original constructor binding drift")
            if (
                helper["source"].split(helper["construction"] + "\n", 1)[1][:-3]
                != item["shallow_branch"]
            ):
                raise ValueError("original source leaf reconstruction drift")
            leaves.append(helper)
    lean = HEADER + operation("serialize", "(Usize × Slice U8)", "U8", True)
    lean += operation("size", "(Bool × Slice Usize)", "Usize", False)
    lean += "\nend BeaconcryptCore.Refinement.RegistrationShallowDispatch\n"
    for operation_name in ("serialize", "size"):
        for endpoint in ("tree", "int", "string", "continuation"):
            name = (
                "BeaconcryptCore.Refinement.RegistrationShallowDispatch."
                + endpoint
                + "_"
                + operation_name
            )
            lean += (
                "\n/-- info: '"
                + name
                + "' depends on axioms: [propext,\n Classical.choice,\n Quot.sound] -/\n#guard_msgs in\n#print axioms "
                + name
                + "\n"
            )
    manifest = {
        "format": 1,
        "checked_lean_sha256": checkpoint.digest(lean.encode()),
        "source_sha256": source["source_sha256"],
        "certificate_generator_sha256": checkpoint.digest(
            (root / "scripts/certify_registration_shallow_dispatch.py").read_bytes()
        ),
        "extracted_source_provenance_sha256": checkpoint.digest(
            (destination / "provenance.json").read_bytes()
        ),
        "control": dispatchers,
        "typed_constructor_leaves": leaves,
        "guard_interpretation": "original actual compute_deep effect followed by Bool branch; both source branches retain original typed mutable poststate",
        "leaf_interpretation": "exact original shallow branch copied after the typed constructor binding; other constructors and entire original deep branch are universally quantified effects",
        "proved_scope": "reachable constructor control/leaf substitution and complete effectful continuation",
        "whole_generic_dispatcher_extracted": False,
        "public_codec_law_proved": False,
        "native_codec_instance_proved": False,
        "generated_rust_files_unchanged": True,
    }
    return lean, manifest


def check(
    root: Path = ROOT, lean_path: Path | None = None, manifest_path: Path | None = None
) -> None:
    lean, manifest = expected(root)
    path = lean_path or root / LEAN
    actual = path.read_text()
    if actual != lean:
        raise ValueError("source guard-tree/leaf instantiation drift")
    if json.loads((manifest_path or root / MANIFEST).read_text()) != manifest:
        raise ValueError("source control correspondence provenance drift")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    try:
        if args.write:
            lean, manifest = expected()
            (ROOT / LEAN).write_text(lean)
            (ROOT / MANIFEST).write_text(
                json.dumps(manifest, indent=2, sort_keys=True) + "\n"
            )
        else:
            check()
        print("Original source control and exact extracted constructor leaves match")
        return 0
    except (OSError, ValueError, TypeError, KeyError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
