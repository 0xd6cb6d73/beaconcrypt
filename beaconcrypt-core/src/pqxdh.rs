/// Accept a verified InitKex without committing any peer or counter state.
pub fn server_accept(
	state: ServerState,
	registration: VerifiedInitKex,
	registration_status: RegistrationStatus,
	server_binding: ServerBinding,
	coins: ServerCoins,
	shared_secrets: &PqxdhSharedSecrets,
) -> Result<(ServerState, PendingServerRegistration), RegistrationError> {
	match validate_registration_status(registration_status) {
		Ok(_) => {}
		Err(err) => return Err(err),
	};
	let root_key_input = match build_root_key_input(shared_secrets) {
		Ok(value) => value,
		Err(err) => return Err(err),
	};
	Ok((
		state,
		PendingServerRegistration {
			server_binding,
			registration_id: registration_id(&registration),
			beacon_identity_public_key: registration.beacon_identity_public_key,
			ephemeral_public_key: coins.ephemeral_public_key,
			kem_ciphertext: coins.kem_ciphertext,
			root_key_input,
		},
	))
}

