/// Construct the exact tagged InitKex payloads from explicit generated
/// material and advance the beacon to its single pending registration.
pub fn beacon_start(
	state: BeaconFresh,
	inputs: BeaconStartInputs,
	coins: BeaconCoins,
) -> BeaconStart {
	BeaconStart {
		state: BeaconInitSent {
			expected_server_binding: state.expected_server_binding,
			beacon_identity_public_key: inputs.identity_public_key,
		},
		message: InitKex {
			identity_key: tag_sign_key(inputs.identity_public_key),
			prekey: tag_x25519_key(KEY_ROLE_PREKEY, inputs.prekey_public_key),
			one_time_key: tag_x25519_key(KEY_ROLE_ONE_TIME, coins.one_time_public_key),
			pq_key: tag_mlkem768_key(inputs.pq_public_key),
		},
	}
}

/// Re-establish typed, verified registration keys after signature checks in
/// the adapter. Incorrect type tags or X25519 field roles are rejected here.
pub fn validate_init_kex(message: InitKex) -> Result<VerifiedInitKex, RegistrationError> {
	let Some(identity) = untag_sign_key(message.identity_key) else {
		return Err(RegistrationError::InvalidKeyEncoding);
	};
	let Some(prekey) = untag_x25519_key(message.prekey, KEY_ROLE_PREKEY) else {
		return Err(RegistrationError::InvalidKeyEncoding);
	};
	let Some(one_time) = untag_x25519_key(message.one_time_key, KEY_ROLE_ONE_TIME) else {
		return Err(RegistrationError::InvalidKeyEncoding);
	};
	let Some(pq) = untag_mlkem768_key(message.pq_key) else {
		return Err(RegistrationError::InvalidKeyEncoding);
	};

	Ok(VerifiedInitKex {
		beacon_identity_public_key: identity,
		beacon_prekey_public_key: prekey,
		beacon_one_time_public_key: one_time,
		beacon_pq_public_key: pq,
	})
}

/// Four classical DH results followed by the post-quantum KEM secret.
pub struct PqxdhSharedSecrets {
	pub dh1: [u8; DH_SECRET_SIZE],
	pub dh2: [u8; DH_SECRET_SIZE],
	pub dh3: [u8; DH_SECRET_SIZE],
	pub dh4: [u8; DH_SECRET_SIZE],
	pub kem_shared_secret: [u8; SHARED_SECRET_SIZE],
}

/// Exact `Padding || DH1 || DH2 || DH3 || DH4 || SS` input to the opaque
/// PQXDH HKDF operation.
pub struct RootKeyInput {
	bytes: [u8; ROOT_KEY_INPUT_SIZE],
}

impl RootKeyInput {
	pub const fn as_bytes(&self) -> &[u8; ROOT_KEY_INPUT_SIZE] {
		&self.bytes
	}

	/// Mutable access is reserved for the production adapter's zeroization of
	/// the concrete transcript immediately after the opaque HKDF call.
	pub fn as_mut_bytes(&mut self) -> &mut [u8; ROOT_KEY_INPUT_SIZE] {
		&mut self.bytes
	}
}

#[cfg_attr(
	feature = "proverif",
	hax_lib::proverif::replace(
		"reduc forall dh1: bitstring, dh2: bitstring, dh3: bitstring, dh4: bitstring, kem: bitstring;\n  ${build_root_key_input}(beaconcrypt_protocol_core__pqxdh__PqxdhSharedSecrets(dh1, dh2, dh3, dh4, kem)) = beaconcrypt_protocol_core__pqxdh__RootKeyInput(pqxdh_root_input(dh1, dh2, dh3, dh4, kem))."
	)
)]
pub fn build_root_key_input(
	secrets: &PqxdhSharedSecrets,
) -> Result<RootKeyInput, RegistrationError> {
	if is_all_zero(&secrets.dh1)
		|| is_all_zero(&secrets.dh2)
		|| is_all_zero(&secrets.dh3)
		|| is_all_zero(&secrets.dh4)
	{
		return Err(RegistrationError::InvalidDhOutput);
	}

	let mut bytes = [0xff; ROOT_KEY_INPUT_SIZE];
	bytes[32..64].copy_from_slice(&secrets.dh1);
	bytes[64..96].copy_from_slice(&secrets.dh2);
	bytes[96..128].copy_from_slice(&secrets.dh3);
	bytes[128..160].copy_from_slice(&secrets.dh4);
	bytes[160..192].copy_from_slice(&secrets.kem_shared_secret);
	Ok(RootKeyInput { bytes })
}

/// The core-owned direction plan for splitting the opaque 64-byte ratchet
/// KDF result. Offsets are bytes into `LHS || RHS`.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RatchetInitialization {
	send_offset: u8,
	receive_offset: u8,
}

impl RatchetInitialization {
	pub const fn send_offset(&self) -> u8 {
		self.send_offset
	}

	pub const fn receive_offset(&self) -> u8 {
		self.receive_offset
	}
}

const BEACON_RATCHETS: RatchetInitialization = RatchetInitialization {
	send_offset: RATCHET_CHAIN_SIZE as u8,
	receive_offset: 0,
};
const SERVER_RATCHETS: RatchetInitialization = RatchetInitialization {
	send_offset: 0,
	receive_offset: RATCHET_CHAIN_SIZE as u8,
};

/// Test and adapter utility for non-handshake ratchet fixtures. Production
/// PQXDH code obtains the same plan from a beacon candidate typestate.
pub const fn beacon_ratchet_initialization() -> RatchetInitialization {
	BEACON_RATCHETS
}

/// Test and adapter utility for non-handshake ratchet fixtures. Production
/// PQXDH code obtains the same plan from a server candidate typestate.
pub const fn server_ratchet_initialization() -> RatchetInitialization {
	SERVER_RATCHETS
}

/// Role-ordered fixed-width initial send and receive chains.
pub struct InitialRatchetChains {
	send_chain: crate::ratchet::RatchetChain,
	receive_chain: crate::ratchet::RatchetChain,
}

/// Fixed-output executor for expanding one authenticated session root into
/// the two initial directional chain values.
pub type InitialRatchetKdfExecutor =
	fn(&crate::ratchet::SymmetricRatchetKdfRequest) -> [u8; INITIAL_RATCHET_KDF_OUTPUT_SIZE];

impl InitialRatchetChains {
	pub const fn send_chain(&self) -> &crate::ratchet::RatchetChain {
		&self.send_chain
	}

	pub const fn receive_chain(&self) -> &crate::ratchet::RatchetChain {
		&self.receive_chain
	}

	pub fn into_parts(self) -> (crate::ratchet::RatchetChain, crate::ratchet::RatchetChain) {
		(self.send_chain, self.receive_chain)
	}
}

/// Split an opaque 64-byte initial expansion into role-ordered fixed-width chains.
pub fn split_initial_ratchet_kdf_output(
	output: &[u8; INITIAL_RATCHET_KDF_OUTPUT_SIZE],
	initialization: RatchetInitialization,
) -> InitialRatchetChains {
	let mut left = [0u8; RATCHET_CHAIN_SIZE];
	left.copy_from_slice(&output[0..32]);
	let mut right = [0u8; RATCHET_CHAIN_SIZE];
	right.copy_from_slice(&output[32..64]);
	if initialization.send_offset == 0 {
		InitialRatchetChains {
			send_chain: crate::ratchet::RatchetChain::from_bytes(left),
			receive_chain: crate::ratchet::RatchetChain::from_bytes(right),
		}
	} else {
		InitialRatchetChains {
			send_chain: crate::ratchet::RatchetChain::from_bytes(right),
			receive_chain: crate::ratchet::RatchetChain::from_bytes(left),
		}
	}
}

/// Apply the sole opaque initial-chain primitive to the exact session root and order its output.
///
/// The primitive's complete production-facing type is `32-byte root -> 64-byte output`.
/// Label selection and HKDF details are private to that domain-specific primitive.
/// Input selection, output size, role ordering, partitioning, and fixed-width construction are owned here.
pub fn derive_initial_ratchet_chains(
	root: &[u8; RATCHET_CHAIN_SIZE],
	initialization: RatchetInitialization,
	kdf: InitialRatchetKdfExecutor,
) -> InitialRatchetChains {
	let request = crate::ratchet::SymmetricRatchetKdfRequest::new(*root);
	let output = kdf(&request);
	split_initial_ratchet_kdf_output(&output, initialization)
}

/// Construct a concrete kernel directly from one root, one fixed role plan,
/// and the executors for initial and subsequent core-owned KDF requests.
pub fn derive_initial_ratchet_kernel(
	root: &[u8; RATCHET_CHAIN_SIZE],
	initialization: RatchetInitialization,
	initial_kdf: InitialRatchetKdfExecutor,
	ratchet_kdf: crate::ratchet::RatchetKdfExecutor,
) -> crate::ratchet::ConcreteRatchetKernel {
	let chains = derive_initial_ratchet_chains(root, initialization, initial_kdf);
	let (send_chain, receive_chain) = chains.into_parts();
	crate::ratchet::ConcreteRatchetKernel::new(send_chain, receive_chain, ratchet_kdf)
}

/// Construct the beacon role's complementary concrete kernel.
pub fn derive_beacon_ratchet_kernel(
	root: &[u8; RATCHET_CHAIN_SIZE],
	initial_kdf: InitialRatchetKdfExecutor,
	ratchet_kdf: crate::ratchet::RatchetKdfExecutor,
) -> crate::ratchet::ConcreteRatchetKernel {
	derive_initial_ratchet_kernel(root, BEACON_RATCHETS, initial_kdf, ratchet_kdf)
}

/// Construct the server role's complementary concrete kernel.
pub fn derive_server_ratchet_kernel(
	root: &[u8; RATCHET_CHAIN_SIZE],
	initial_kdf: InitialRatchetKdfExecutor,
	ratchet_kdf: crate::ratchet::RatchetKdfExecutor,
) -> crate::ratchet::ConcreteRatchetKernel {
	derive_initial_ratchet_kernel(root, SERVER_RATCHETS, initial_kdf, ratchet_kdf)
}

/// Candidate beacon session. Its root, AD, identity assignment, and ratchet
/// direction have been validated, but its initial ciphertext has not yet
/// authenticated. It must be consumed by [`beacon_commit`] or
/// [`beacon_abort_candidate`].
pub struct BeaconRegistrationCandidate {
	server_binding: ServerBinding,
	assigned_key_id: u64,
	root_key_input: RootKeyInput,
	associated_data: [u8; ASSOCIATED_DATA_SIZE],
}

impl BeaconRegistrationCandidate {
	pub const fn server_key_id(&self) -> u64 {
		self.server_binding.identity_key_id
	}

	pub const fn server_binding(&self) -> ServerBinding {
		self.server_binding
	}

	pub const fn assigned_key_id(&self) -> u64 {
		self.assigned_key_id
	}

	pub const fn root_key_input(&self) -> &RootKeyInput {
		&self.root_key_input
	}

	pub fn root_key_input_mut(&mut self) -> &mut RootKeyInput {
		&mut self.root_key_input
	}

	pub const fn associated_data(&self) -> &[u8; ASSOCIATED_DATA_SIZE] {
		&self.associated_data
	}

	pub const fn ratchet_initialization(&self) -> RatchetInitialization {
		BEACON_RATCHETS
	}

	pub const fn key_id_binding(&self) -> RegistrationKeyIdBinding {
		registration_key_id_binding(self.assigned_key_id)
	}

	/// Bind the authenticated candidate's beacon direction directly to a
	/// concrete core ratchet kernel.
	pub fn derive_ratchet_kernel(
		&self,
		root: &[u8; RATCHET_CHAIN_SIZE],
		initial_kdf: InitialRatchetKdfExecutor,
		ratchet_kdf: crate::ratchet::RatchetKdfExecutor,
	) -> crate::ratchet::ConcreteRatchetKernel {
		derive_beacon_ratchet_kernel(root, initial_kdf, ratchet_kdf)
	}
}

pub struct BeaconFinishInputs {
	pub response_server_identity: [u8; SIGN_PUBLIC_KEY_SIZE],
	pub assigned_key_id: u64,
	pub shared_secrets: PqxdhSharedSecrets,
}

pub fn beacon_prepare_finish(
	state: BeaconInitSent,
	inputs: &BeaconFinishInputs,
) -> Result<BeaconRegistrationCandidate, RegistrationError> {
	if state.expected_server_binding.identity_public_key != inputs.response_server_identity {
		return Err(RegistrationError::IdentityMismatch);
	}
	let root_key_input = build_root_key_input(&inputs.shared_secrets)?;
	let associated_data = build_associated_data(
		state.expected_server_binding.identity_public_key,
		state.beacon_identity_public_key,
	);
	Ok(BeaconRegistrationCandidate {
		server_binding: state.expected_server_binding,
		assigned_key_id: inputs.assigned_key_id,
		root_key_input,
		associated_data,
	})
}

/// Fixed-width authenticated binding carried inside the encrypted initial
/// registration payload. The adapter strips it before returning application
/// plaintext.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RegistrationKeyIdBinding {
	bytes: [u8; REGISTRATION_KEY_ID_BINDING_SIZE],
}

impl RegistrationKeyIdBinding {
	pub const fn as_bytes(&self) -> &[u8; REGISTRATION_KEY_ID_BINDING_SIZE] {
		&self.bytes
	}
}

pub const fn registration_key_id_binding(key_id: u64) -> RegistrationKeyIdBinding {
	RegistrationKeyIdBinding {
		bytes: [
			key_id as u8,
			(key_id >> 8) as u8,
			(key_id >> 16) as u8,
			(key_id >> 24) as u8,
			(key_id >> 32) as u8,
			(key_id >> 40) as u8,
			(key_id >> 48) as u8,
			(key_id >> 56) as u8,
		],
	}
}

