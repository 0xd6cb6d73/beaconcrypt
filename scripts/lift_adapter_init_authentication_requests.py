def transform(source: bytes) -> bytes:
    text = source.decode()
    result = []
    for label, start, stop, reviewed in SELECTED:
        if text.count(start) != 1 or text.count(stop) != 1:
            raise ValueError("selected Init source declaration roster changed")
        body = start + text.split(start, 1)[1].split(stop, 1)[0].rstrip() + "\n"
        if hashlib.sha256(body.encode()).hexdigest() != reviewed:
            raise ValueError("reviewed Init source body changed")
        if re.search(r"\b(?:sorry|admit|axiom|opaque|unsafe|partial)\b", body):
            raise ValueError("unchecked source declaration")
        for before, after, count in REPLACEMENTS[label]:
            if body.count(before) != count:
                raise ValueError("source Init leaf multiplicity changed: " + before)
            body = body.replace(before, after)
        if re.search(
            r"\b(?:RustM|lift|ok)\b|auth\.(?:execute_hash|verify_requested)|core\.option\.Option\.as_deref",
            body,
        ):
            raise ValueError("unlifted Init source leaf")
        result.append(body)
    return (
        HEADER
        + "-- Extracted input SHA-256: "
        + hashlib.sha256(source).hexdigest()
        + "\n"
        + "-- Transformation SHA-256: "
        + hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
        + "\n"
        + "\n".join(result)
        + "\nend BeaconcryptCore.Refinement.AdapterInitAuthenticationRequestExtraction\n"
    ).encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = transform((ROOT / SOURCE).read_bytes())
    path = ROOT / DESTINATION
    if args.write:
        path.write_bytes(expected)
    elif not path.exists() or path.read_bytes() != expected:
        parser.error("Init request extraction differs; review with --write")
    print("Init authentication requests match both original extracted source bodies")
    return 0


