#!/usr/bin/env python3
"""Expose exactly the extracted Builder record subtree as a private observer hole."""

from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = (
    ROOT
    / "beaconcrypt-core/proofs/lean/BeaconcryptCore/AdapterPublicWrapperRequestExtraction.lean"
)
TARGET = (
    ROOT
    / "beaconcrypt-core/proofs/lean/BeaconcryptCore/AdapterPublicBuildObservedExtraction.lean"
)
NAME = "server.Server.Insts.BeaconcryptServerProviderServer.build_registration_response"
BRANCH = "          | core.ops.control_flow.ControlFlow.Continue _ =>\n"
END = "\n          | core.ops.control_flow.ControlFlow.Break residual =>"


def render() -> str:
    text = SOURCE.read_text()
    start = text.index("def\n  " + NAME + "\n")
    stop = text.index("\n\n\nend beaconcrypt_public_request", start)
    body = text[start:stop].rstrip()
    if body.count(BRANCH) != 1:
        raise ValueError("Expected exactly one literal reserved-success record subtree")
    first = body.index(BRANCH) + len(BRANCH)
    last = body.index(END, first)
    cut = body[first:last]
    expected = (
        "beaconcrypt_core.registration.ServerInitialKdf.request",
        "ratchet_initial_ratchet_hkdf",
        "beaconcrypt_core.registration.ServerInitialKdf.resume",
        "ratchet_execute_seal_request",
        "ratchet_execute_write_request",
        "auth_MldsaIdentity_sign_requested",
        "ChildOperations.encodeResponse",
        "beaconcrypt_core.peer.begin_peer_insert",
    )
    if any(cut.count(word) != 1 for word in expected):
        raise ValueError("The isolated literal Builder record subtree changed")
    body = (
        body[:first]
        + "            completion { self with known_ids := hm } val2"
        + body[last:]
    )
    body = body.replace(
        "def\n  " + NAME + "\n",
        "def run\n  (completion : beaconcrypt_public_wrapper.server.Server → beaconcrypt_core.registration.ServerInitialKdf →\n    m ((core.option.Option beaconcrypt_public_wrapper.server.RegResponse) × beaconcrypt_public_wrapper.server.Server))\n",
        1,
    )
    variables = text[
        text.index(
            "variable [BeaconcryptCore.Refinement.PublicWrapperPlatform.Material]"
        ) : text.index("/-- [beaconcrypt::auth::fingerprint_pin]")
    ]
    digest = hashlib.sha256(text[start:stop].encode()).hexdigest()
    cut_digest = hashlib.sha256(cut.encode()).hexdigest()
    transform_digest = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    return f"""-- SPDX-License-Identifier: 0BSD
-- Generated by scripts/lift_adapter_build_observed.py; do not edit.
-- Transformation script SHA-256: {transform_digest}
-- Source lifted Builder AST SHA-256: {digest}
-- Isolated literal completion subtree SHA-256: {cut_digest}
import BeaconcryptCore.AdapterPublicWrapperRequestExtraction
open CoreModels Aeneas
open Aeneas.Std hiding namespace core alloc
open RustM ControlFlow Error
open Std.Do
open beaconcrypt_public_wrapper
set_option autoImplicit false
set_option warningAsError true
set_option maxHeartbeats 1000000
set_option maxRecDepth 4096
noncomputable section
namespace BeaconcryptCore.Refinement.AdapterPublicBuildObservedRequest
{variables}
{body}

end BeaconcryptCore.Refinement.AdapterPublicBuildObservedRequest
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    fresh = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != fresh:
            raise SystemExit(
                "Builder observer AST differs from the current extracted source; regenerate and review"
            )
        print("Builder observer AST fresh comparison PASS")
    else:
        TARGET.write_text(fresh)


if __name__ == "__main__":
    main()
