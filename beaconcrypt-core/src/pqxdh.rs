#[derive(Clone, Copy)]
#[cfg_attr(not(hax_compilation), derive(Debug, Eq, PartialEq))]
pub enum KeyIdAvailability {
	Available,
	Occupied,
}

/// Return the next key ID without wrapping an exhausted counter.
pub const fn server_next_key_id(state: ServerState) -> Result<u64, RegistrationError> {
	if state.last_key_id == u64::MAX {
		Err(RegistrationError::KeyIdExhausted)
	} else {
		Ok(state.last_key_id + 1)
	}
}

/// Prepare the next checked, explicitly unoccupied server key ID.
pub fn server_prepare_commit(
	state: ServerState,
	pending: PendingServerRegistration,
	current_server_binding: ServerBinding,
	key_id_availability: KeyIdAvailability,
) -> Result<ServerRegistrationCandidate, RegistrationError> {
	if !(pending.server_binding.identity_key_id == current_server_binding.identity_key_id)
		|| !(pending.server_binding.identity_public_key
			== current_server_binding.identity_public_key)
	{
		return Err(RegistrationError::IdentityMismatch);
	}
	let key_id = match server_next_key_id(state) {
		Ok(value) => value,
		Err(err) => return Err(err),
	};
	if matches!(key_id_availability, KeyIdAvailability::Occupied) {
		return Err(RegistrationError::KeyIdCollision);
	}
	Ok(ServerRegistrationCandidate {
		previous_state: state,
		next_state: ServerState {
			last_key_id: key_id,
		},
		key_id,
		beacon_identity_public_key: pending.beacon_identity_public_key,
		server_identity_public_key: current_server_binding.identity_public_key,
		server_identity_key_id: current_server_binding.identity_key_id,
		ephemeral_public_key: pending.ephemeral_public_key,
		kem_ciphertext: pending.kem_ciphertext,
		associated_data: build_associated_data(
			current_server_binding.identity_public_key,
			pending.beacon_identity_public_key,
		),
	})
}

