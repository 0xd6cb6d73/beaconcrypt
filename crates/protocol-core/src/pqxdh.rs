	#[test]
	fn beacon_candidate_commits_or_aborts_explicitly() {
		let expected_server = server_binding(9, 0x91);
		let started = beacon_start(
			BeaconFresh::new(expected_server),
			BeaconStartInputs {
				identity_public_key: [0x81; SIGN_PUBLIC_KEY_SIZE],
				prekey_public_key: [0x82; X25519_PUBLIC_KEY_SIZE],
				pq_public_key: [0x83; MLKEM768_PUBLIC_KEY_SIZE],
			},
			BeaconCoins {
				one_time_public_key: [0x84; X25519_PUBLIC_KEY_SIZE],
			},
		);
		let candidate = || {
			let inputs = BeaconFinishInputs {
				response_server_identity: [0x91; SIGN_PUBLIC_KEY_SIZE],
				assigned_key_id: 12,
				shared_secrets: shared_secrets(),
			};
			beacon_prepare_finish(started.state, &inputs).unwrap()
		};
		assert_eq!(started.state.expected_server_binding(), expected_server);
		assert_eq!(started.state.server_key_id(), 9);
		assert_eq!(candidate().server_binding(), expected_server);
		assert_eq!(candidate().server_key_id(), 9);
		assert_eq!(candidate().assigned_key_id(), 12);
		for response_server_identity in [[0x90; SIGN_PUBLIC_KEY_SIZE], [0x92; SIGN_PUBLIC_KEY_SIZE]]
		{
			assert!(matches!(
				beacon_prepare_finish(
					started.state,
					&BeaconFinishInputs {
						response_server_identity,
						assigned_key_id: 12,
						shared_secrets: shared_secrets(),
					},
				),
				Err(RegistrationError::IdentityMismatch)
			));
		}
		let candidate_for_binding = candidate();
		assert_eq!(
			candidate_for_binding.key_id_binding().as_bytes(),
			&12u64.to_le_bytes()
		);
		assert!(
			authenticate_registration_key_id_binding(
				candidate_for_binding,
				expected_server.identity_key_id,
				12u64.to_le_bytes(),
			)
			.is_ok()
		);
		assert!(matches!(
			authenticate_registration_key_id_binding(
				candidate(),
				expected_server.identity_key_id,
				13u64.to_le_bytes(),
			),
			Err(RegistrationError::KeyIdMismatch)
		));
		assert!(matches!(
			authenticate_registration_key_id_binding(
				candidate(),
				expected_server.identity_key_id + 1,
				12u64.to_le_bytes(),
			),
			Err(RegistrationError::IdentityMismatch)
		));
		let authenticated = authenticate_registration_key_id_binding(
			candidate(),
			expected_server.identity_key_id,
			12u64.to_le_bytes(),
		)
		.unwrap();
		assert_eq!(authenticated.server_key_id(), 9);
		let established = beacon_commit(authenticated);
		assert_eq!(established.assigned_key_id(), 12);
		assert_eq!(established.server_key_id(), 9);
		assert_eq!(established.server_binding(), expected_server);
		assert_eq!(beacon_abort_candidate(candidate()).server_key_id(), 9);
	}

	#[test]
	fn server_candidate_does_not_commit_until_explicit_completion() {
		let verified = validate_init_kex(init_message()).unwrap();
		let state = ServerState::new(4);
		let secrets = shared_secrets();
		let (unchanged, pending) = server_accept(
			state,
			verified,
			RegistrationStatus::Fresh,
			ServerBinding {
				identity_public_key: [0xa3; SIGN_PUBLIC_KEY_SIZE],
				identity_key_id: 3,
			},
			ServerCoins {
				ephemeral_public_key: [0xa1; X25519_PUBLIC_KEY_SIZE],
				kem_ciphertext: [0xa2; MLKEM768_CIPHERTEXT_SIZE],
			},
			&secrets,
		)
		.unwrap();
		assert_eq!(unchanged, state);
		let (_, mismatched_pending) = server_accept(
			state,
			verified,
			RegistrationStatus::Fresh,
			ServerBinding {
				identity_public_key: [0xa3; SIGN_PUBLIC_KEY_SIZE],
				identity_key_id: 3,
			},
			ServerCoins {
				ephemeral_public_key: [0xa1; X25519_PUBLIC_KEY_SIZE],
				kem_ciphertext: [0xa2; MLKEM768_CIPHERTEXT_SIZE],
			},
			&secrets,
		)
		.unwrap();
		assert!(matches!(
			server_prepare_commit(
				state,
				mismatched_pending,
				ServerBinding {
					identity_public_key: [0xb3; SIGN_PUBLIC_KEY_SIZE],
					identity_key_id: 3,
				},
				KeyIdAvailability::Available,
			),
			Err(RegistrationError::IdentityMismatch)
		));
		let (_, mismatched_key_id_pending) = server_accept(
			state,
			verified,
			RegistrationStatus::Fresh,
			ServerBinding {
				identity_public_key: [0xa3; SIGN_PUBLIC_KEY_SIZE],
				identity_key_id: 3,
			},
			ServerCoins {
				ephemeral_public_key: [0xa1; X25519_PUBLIC_KEY_SIZE],
				kem_ciphertext: [0xa2; MLKEM768_CIPHERTEXT_SIZE],
			},
			&secrets,
		)
		.unwrap();
		assert!(matches!(
			server_prepare_commit(
				state,
				mismatched_key_id_pending,
				ServerBinding {
					identity_public_key: [0xa3; SIGN_PUBLIC_KEY_SIZE],
					identity_key_id: 4,
				},
				KeyIdAvailability::Available,
			),
			Err(RegistrationError::IdentityMismatch)
		));
		let candidate = server_prepare_commit(
			unchanged,
			pending,
			ServerBinding {
				identity_public_key: [0xa3; SIGN_PUBLIC_KEY_SIZE],
				identity_key_id: 3,
			},
			KeyIdAvailability::Available,
		)
		.unwrap();
		assert_eq!(candidate.key_id_binding().as_bytes(), &5u64.to_le_bytes());
		assert_eq!(server_abort_candidate(&candidate), state);
		let (committed, peer) = server_commit(candidate);
		assert_eq!(committed.last_key_id(), 5);
		assert_eq!(peer.key_id, 5);
	}

