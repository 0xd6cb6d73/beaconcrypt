"""Lift the selected extracted receive-loop body, without rewriting its control flow.

Only the reviewed monadic leaves are replaced. Unknown leaves, missing leaves,
duplicate leaves, declaration changes and primitive-roster changes fail closed.
The generated RustM specialization is checked against the original declaration
by the Lean kernel in AdapterRecordStatefulReceive.body_specializes.
"""

