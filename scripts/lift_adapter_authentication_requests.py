"""Lift the actual extracted response-authentication body into requests.

The complete reviewed body fingerprint and leaf multiplicities fail closed.
Only monadic core leaves and the hash and verification primitive calls are replaced; matches,
request order, residual exits and returned protocol fields are retained.
The RustM specialization is independently checked against the original source
by AdapterAuthenticationStatefulResponse.controller_specializes.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(
    "beaconcrypt-core/proofs/lean/BeaconcryptCore/AdapterAuthenticationExtraction/Funs.lean"
)
DESTINATION = Path(
    "beaconcrypt-core/proofs/lean/BeaconcryptCore/AdapterAuthenticationRequestExtraction.lean"
)
START = "def auth.authenticate_response"
STOP = "\nend beaconcrypt"
REVIEWED_BODY_SHA256 = (
    "424eefd55a99fde2aade11be1e45b0b1565240638676a4d41daa4d12994bb75b"
)
REPLACEMENTS = (
    (START, "def authenticate", 1),
    ("RustM (core.result.Result", "m (core.result.Result", 1),
    ("beaconcrypt_core.registration.begin_response_authentication", "Lifted.begin", 1),
    ("core.result.Result.Insts.CoreOpsTry_traitTry.branch", "Lifted.branch", 3),
    ("beaconcrypt_core.registration.ResponseHash.request", "Lifted.hashRequest", 1),
    ("beaconcrypt_core.registration.ResponseHash.resume", "Lifted.hashResume", 1),
    (
        "beaconcrypt_core.registration.ResponseMldsaVerification.request",
        "Lifted.verifyRequest",
        1,
    ),
    (
        "beaconcrypt_core.registration.ResponseMldsaVerification.resume",
        "Lifted.verifyResume",
        1,
    ),
    ("beaconcrypt_core.registration.BeaconAdHash.request", "Lifted.adHashRequest", 1),
    ("beaconcrypt_core.registration.BeaconAdHash.resume", "Lifted.adHashResume", 1),
    ("auth.execute_hash", "Operations.hash", 2),
    ("auth.verify_requested", "Operations.verify", 1),
)
RESIDUAL = (
    r"core\.result\.Result\.Insts\.CoreOpsTry_traitFromResidualResultInfallibleE\.from_residual"
    r"\s+beaconcrypt_core\.registration\.AuthenticatedResponse"
    r"\s+\(core\.convert\.From\.Blanket beaconcrypt_core\.pqxdh\.BeaconAborted\)"
    r"\s+residual"
)
HEADER = """-- SPDX-License-Identifier: 0BSD
-- Generated by scripts/lift_adapter_authentication_requests.py; do not edit.
import BeaconcryptCore.Refinement.AdapterAuthenticationRequestMonad

open CoreModels Aeneas OracleComp
open Aeneas.Std hiding namespace core alloc
open RustM ControlFlow beaconcrypt_core
open Std.Do

set_option autoImplicit false
set_option warningAsError true

namespace BeaconcryptCore.Refinement.AdapterAuthenticationRequestExtraction
open AdapterAuthenticationRequestMonad
open AdapterRecordRequestMonad (LiftRust)
variable {m : Type → Type} [Monad m] [LiftRust m] [Operations m]

"""
FOOTER = "\nend BeaconcryptCore.Refinement.AdapterAuthenticationRequestExtraction\n"


def transform(source: bytes) -> bytes:
    text = source.decode()
    if text.count(START) != 1 or text.count(STOP) != 1:
        raise ValueError("expected one selected extracted response-authentication body")
    body = START + text.split(START, 1)[1].split(STOP, 1)[0].rstrip() + "\n"
    if hashlib.sha256(body.encode()).hexdigest() != REVIEWED_BODY_SHA256:
        raise ValueError(
            "selected extracted body changed; review its control flow before updating its fingerprint"
        )
    if re.search(r"\b(?:sorry|admit|axiom|opaque|unsafe|partial)\b", body):
        raise ValueError("unchecked declaration in extracted body")
    if len(re.findall(r"^def\b", body, re.M)) != 1:
        raise ValueError("unexpected declaration roster")
    for old, new, expected in REPLACEMENTS:
        if body.count(old) != expected:
            raise ValueError(f"reviewed leaf {old!r} changed multiplicity")
        body = body.replace(old, new)
    body, count = re.subn(RESIDUAL, "Lifted.fromResidual residual", body)
    if count != 3:
        raise ValueError("reviewed residual return leaf changed multiplicity")
    if re.search(
        r"\b(?:RustM|auth)\.|(?:registration\.[A-Za-z]+\.(?:request|resume))|from_residual",
        body,
    ):
        raise ValueError("unlifted monadic leaf remains")
    source_hash = hashlib.sha256(source).hexdigest()
    transformer_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    return (
        HEADER
        + f"-- Extracted input SHA-256: {source_hash}\n"
        + f"-- Transformation SHA-256: {transformer_hash}\n"
        + body
        + FOOTER
    ).encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = transform((ROOT / SOURCE).read_bytes())
    destination = ROOT / DESTINATION
    if args.write:
        destination.write_bytes(expected)
    elif not destination.exists() or destination.read_bytes() != expected:
        parser.error(
            "request extraction differs; review the generated diff with --write"
        )
    print(
        "adapter authentication request extraction matches the selected extracted body"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
