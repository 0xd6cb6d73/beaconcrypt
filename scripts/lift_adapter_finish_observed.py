#!/usr/bin/env python3
"""Expose exactly the extracted Finish completion subtree as a private observer hole."""

from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = (
    ROOT
    / "beaconcrypt-core/proofs/lean/BeaconcryptCore/AdapterPublicWrapperRequestExtraction.lean"
)
TARGET = (
    ROOT
    / "beaconcrypt-core/proofs/lean/BeaconcryptCore/AdapterPublicFinishObservedExtraction.lean"
)
NAME = "beacon.Beacon.Insts.BeaconcryptBeaconProviderBeacon.finish_registration"
BRANCH = "        | beaconcrypt_core.agreement.AgreementEffect.BeaconComplete agreement\n          =>\n"
END = "\n      | core.result.Result.Err control =>"


def render() -> str:
    text = SOURCE.read_text()
    start = text.index("def " + NAME + "\n")
    stop = text.index("\n\nabbrev collections.", start)
    body = text[start:stop].rstrip()
    if body.count(BRANCH) != 1:
        raise ValueError("Expected exactly one literal BeaconComplete subtree")
    first = body.index(BRANCH) + len(BRANCH)
    last = body.index(END, first)
    cut = body[first:last]
    expected = (
        "beaconcrypt_core.registration.begin_beacon_completion",
        "beaconcrypt_core.registration.BeaconInitialKdf.request",
        "ratchet_initial_ratchet_hkdf",
        "beaconcrypt_core.registration.BeaconInitialKdf.resume",
        "beaconcrypt_public_request.beacon.Beacon.Insts.BeaconcryptBeaconProviderBeacon.finish_registration_loop",
    )
    if any(cut.count(word) != 1 for word in expected):
        raise ValueError("The isolated literal completion subtree changed")
    body = (
        body[:first]
        + "          completion { self with state := bs } agreement"
        + body[last:]
    )
    body = body.replace(
        "def " + NAME + "\n",
        "def run\n  (completion : beaconcrypt_public_wrapper.beacon.Beacon → beaconcrypt_core.agreement.BeaconAgreement →\n    m ((core.option.Option (alloc.vec.Vec Std.U8)) × beaconcrypt_public_wrapper.beacon.Beacon))\n",
        1,
    )
    variables = text[
        text.index(
            "variable [BeaconcryptCore.Refinement.PublicWrapperPlatform.Material]"
        ) : text.index("/-- [beaconcrypt::auth::fingerprint_pin]")
    ]
    digest = hashlib.sha256(text[start:stop].encode()).hexdigest()
    cut_digest = hashlib.sha256(cut.encode()).hexdigest()
    transform_digest = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    return f"""-- SPDX-License-Identifier: 0BSD
-- Generated by scripts/lift_adapter_finish_observed.py; do not edit.
-- Transformation script SHA-256: {transform_digest}
-- Source lifted Finish AST SHA-256: {digest}
-- Isolated literal completion subtree SHA-256: {cut_digest}
import BeaconcryptCore.AdapterPublicWrapperRequestExtraction
open CoreModels Aeneas
open Aeneas.Std hiding namespace core alloc
open RustM ControlFlow Error
open Std.Do
open beaconcrypt_public_wrapper
set_option autoImplicit false
set_option warningAsError true
set_option maxHeartbeats 1000000
set_option maxRecDepth 4096
noncomputable section
namespace BeaconcryptCore.Refinement.AdapterPublicFinishObservedRequest
{variables}
{body}

end BeaconcryptCore.Refinement.AdapterPublicFinishObservedRequest
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    fresh = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != fresh:
            raise SystemExit(
                "Finish observer AST differs from the current extracted source; regenerate and review"
            )
        print("Finish observer AST fresh comparison PASS")
    else:
        TARGET.write_text(fresh)


if __name__ == "__main__":
    main()
