/// Associated data is always encoded server identity first, beacon identity
/// second, then the key-exchange and ratchet domain-separation strings.
#[cfg_attr(
	feature = "proverif",
	hax_lib::proverif::replace(
		"reduc forall server_identity: bitstring, beacon_identity: bitstring;\n  ${build_associated_data}(server_identity, beacon_identity) = beaconcrypt_associated_data(tag_ed25519(server_identity), tag_ed25519(beacon_identity), pqxdh_domain(), symmetric_ratchet_domain())."
	)
)]
pub fn build_associated_data(
	server_identity_public_key: [u8; SIGN_PUBLIC_KEY_SIZE],
	beacon_identity_public_key: [u8; SIGN_PUBLIC_KEY_SIZE],
) -> [u8; ASSOCIATED_DATA_SIZE] {
	let encoded_server = tag_sign_key(server_identity_public_key);
	let encoded_beacon = tag_sign_key(beacon_identity_public_key);

	let output: [u8; ASSOCIATED_DATA_SIZE] = core::array::from_fn(|i| {
		if i < 33 {
			encoded_server[i]
		} else if i < 66 {
			encoded_beacon[i - 33]
		} else if i < 112 {
			PQXDH_INFO[i - 66]
		} else {
			SYM_RATCHET_INFO[i - 112]
		}
	});
	output
}

fn tag_sign_key(key: [u8; SIGN_PUBLIC_KEY_SIZE]) -> [u8; ENCODED_SIGN_PUBLIC_KEY_SIZE] {
	let output: [u8; ENCODED_SIGN_PUBLIC_KEY_SIZE] =
		core::array::from_fn(|i| if i < 1 { SIGN_TYPE_ED25519 } else { key[i - 1] });
	output
}

fn tag_x25519_key(
	role: u8,
	key: [u8; X25519_PUBLIC_KEY_SIZE],
) -> [u8; ENCODED_X25519_PUBLIC_KEY_SIZE] {
	let output: [u8; ENCODED_X25519_PUBLIC_KEY_SIZE] = core::array::from_fn(|i| {
		if i < 1 {
			KEM_TYPE_X25519
		} else if i < 2 {
			role
		} else {
			key[i - 2]
		}
	});
	output
}

fn tag_mlkem768_key(key: [u8; MLKEM768_PUBLIC_KEY_SIZE]) -> [u8; ENCODED_MLKEM768_PUBLIC_KEY_SIZE] {
	let output: [u8; ENCODED_MLKEM768_PUBLIC_KEY_SIZE] =
		core::array::from_fn(|i| if i < 1 { KEM_TYPE_MLKEM768 } else { key[i - 1] });
	output
}

fn untag_sign_key(
	encoded: [u8; ENCODED_SIGN_PUBLIC_KEY_SIZE],
) -> Option<[u8; SIGN_PUBLIC_KEY_SIZE]> {
	if !(encoded[0] == SIGN_TYPE_ED25519) {
		return None;
	}
	let key: [u8; SIGN_PUBLIC_KEY_SIZE] = core::array::from_fn(|i| encoded[i + 1]);
	Some(key)
}

fn untag_x25519_key(
	encoded: [u8; ENCODED_X25519_PUBLIC_KEY_SIZE],
	expected_role: u8,
) -> Option<[u8; X25519_PUBLIC_KEY_SIZE]> {
	if !(encoded[0] == KEM_TYPE_X25519) || !(encoded[1] == expected_role) {
		return None;
	}
	let key: [u8; X25519_PUBLIC_KEY_SIZE] = core::array::from_fn(|i| encoded[i + 2]);
	Some(key)
}

fn untag_mlkem768_key(
	encoded: [u8; ENCODED_MLKEM768_PUBLIC_KEY_SIZE],
) -> Option<[u8; MLKEM768_PUBLIC_KEY_SIZE]> {
	if !(encoded[0] == KEM_TYPE_MLKEM768) {
		return None;
	}
	let key: [u8; MLKEM768_PUBLIC_KEY_SIZE] = core::array::from_fn(|i| encoded[i + 1]);
	Some(key)
}

fn is_all_zero(bytes: &[u8; DH_SECRET_SIZE]) -> bool {
	*bytes == [0; DH_SECRET_SIZE]
}

