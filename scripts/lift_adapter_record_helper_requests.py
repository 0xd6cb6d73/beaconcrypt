def transform(source: bytes) -> bytes:
    text = source.decode()
    if re.search(
        r"(?m)^\s*(?:axiom|opaque|unsafe|partial)\b|\b(?:sorry|admit)\b", text
    ):
        raise ValueError("unchecked source file declaration")
    output = []
    for name, declaration in DECLARATIONS.items():
        marker = "def " + declaration + "\n"
        if text.count(marker) != 1:
            raise ValueError("record helper declaration roster changed: " + name)
        start = text.index(marker)
        end = text.find("\n/--", start)
        if end < 0:
            end = text.index("\nend beaconcrypt_record_helpers", start)
        body = text[start:end].strip() + "\n"
        if hashlib.sha256(body.encode()).hexdigest() != REVIEWED_BODIES[name]:
            raise ValueError("source record helper changed: " + name)
        if re.search(r"\b(?:sorry|admit|axiom|opaque|unsafe|partial)\b", body):
            raise ValueError("unchecked record helper declaration")
        body = body.replace(marker, "def " + name + "\n")
        for before, after, count in REPLACEMENTS[name]:
            if body.count(before) != count:
                raise ValueError("record helper leaf multiplicity changed: " + before)
            body = body.replace(before, after)
        body, residuals = RESIDUAL.subn("Lifted.fromResidual", body)
        if residuals != 4:
            raise ValueError("record helper residual branch roster changed")
        if re.search(
            r"\b(?:RustM|ok)\b|Array\.index_usize|core\.slice\.Slice\.len|core\.num\.Usize\.checked_add"
            r"|alloc\.vec\.Vec\.(?:new|try_reserve_exact|extend_from_slice)|wire\.encode_record"
            r"|beaconcrypt_core\.transport\.encoded_frame_len|core\.option\.Option\.Insts\.",
            body,
        ):
            raise ValueError("unlifted record helper operation")
        output.append(body)
    return (
        HEADER
        + "-- Extracted input SHA-256: "
        + hashlib.sha256(source).hexdigest()
        + "\n-- Transformation SHA-256: "
        + hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
        + "\n\n"
        + "\n".join(output)
        + "\nend BeaconcryptCore.Refinement.AdapterRecordHelperRequestExtraction\n"
    ).encode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, help="isolated development output path")
    args = parser.parse_args()
    expected = transform((ROOT / SOURCE).read_bytes())
    destination = args.output if args.output is not None else ROOT / DESTINATION
    if args.write:
        destination.write_bytes(expected)
    elif not destination.exists() or destination.read_bytes() != expected:
        parser.error(
            "record helper request extraction differs; review the generated diff"
        )
    print("record helper requests match the reviewed extracted bodies")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
