/// Adapter-supplied result of looking up a registration ID in the persistent
/// consumed-registration set.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RegistrationStatus {
	Fresh,
	Consumed,
}

pub fn validate_registration_status(
	registration_status: RegistrationStatus,
) -> Result<(), RegistrationError> {
	if matches!(registration_status, RegistrationStatus::Consumed) {
		return Err(RegistrationError::RegistrationReplay);
	}
	Ok(())
}

